def classify_category(item_text):
    """품목명 문자열에서 dispute-rules.md의 4개 카테고리 중 하나를 키워드
    매칭으로 추정한다. 매칭되는 키워드가 없으면 None(카테고리별 규칙 주입을
    생략하고 기존 범용 missing_items 체크만 적용됨)."""
    text = item_text or ""
    for category, keywords in _CATEGORY_KEYWORDS.items():
        if any(keyword in text for keyword in keywords):
            return category
    return None


def build_category_prompt_block(item_text):
    """[품목별 확인 포인트] 섹션 텍스트를 만든다. 매칭되는 카테고리가 없으면
    빈 문자열을 반환한다 — build_user_message가 이 경우 섹션 자체를 생략."""
    category = classify_category(item_text)
    if category is None:
        return ""
    lines = [f"[품목별 확인 포인트 — {category}]"]
    lines += [f"- {rule}" for rule in CATEGORY_RULES[category]]
    return "\n".join(lines)
